DROP TABLE IF EXISTS biz_device_comm_event;
DROP TABLE IF EXISTS biz_device_comm_target;
DROP TABLE IF EXISTS biz_device_comm_source;
DROP TABLE IF EXISTS biz_device_comm_policy_audit;
DROP TABLE IF EXISTS biz_device_comm_policy;
-- 统一通讯可用性：不修改采集周期、不发送设备指令，也不以业务补值刷新在线。
CREATE TABLE biz_device_comm_policy (
 scope_key VARCHAR(150) PRIMARY KEY, period_seconds INT NOT NULL, monitored TINYINT NOT NULL,
 evidence VARCHAR(500) NOT NULL, revision BIGINT NOT NULL, updated_by BIGINT,
 CHECK(period_seconds BETWEEN 5 AND 86400), CHECK(monitored IN (0,1)), CHECK(revision>0)
);
CREATE TABLE biz_device_comm_policy_audit (
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scope_key VARCHAR(150) NOT NULL,
 period_seconds INT NOT NULL, monitored TINYINT NOT NULL, evidence VARCHAR(500) NOT NULL,
 revision BIGINT NOT NULL, changed_by BIGINT NOT NULL, gateway_key VARCHAR(240),
 changed_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) NOT NULL,
 UNIQUE KEY uk_comm_policy_audit(scope_key,revision)
);
CREATE TABLE biz_device_comm_source (
 source_key VARCHAR(240) NOT NULL, observer_id VARCHAR(50) NOT NULL, health VARCHAR(20) NOT NULL,
 observed_at BIGINT NOT NULL, lease_until BIGINT NOT NULL, PRIMARY KEY(source_key,observer_id),
 CHECK(health IN ('HEALTHY','FAILED','DOWN')),
 KEY idx_comm_source_lease(source_key,health,lease_until)
);
CREATE TABLE biz_device_comm_target (
 identity_id VARCHAR(32) PRIMARY KEY, equip_id VARCHAR(32) NOT NULL, building_id VARCHAR(32) NOT NULL,
 source_key VARCHAR(240) NOT NULL, scope_token CHAR(64) NOT NULL, scope_profile VARCHAR(100) NOT NULL,
 scope_product VARCHAR(32), scope_identity VARCHAR(200) NOT NULL, identity_updated TIMESTAMP(6),
 mapping_revision INT NOT NULL DEFAULT 0, gateway_key VARCHAR(240), gateway_revision BIGINT NOT NULL DEFAULT 0,
 monitored TINYINT NOT NULL, monitoring_since BIGINT NOT NULL, period_seconds INT NOT NULL,
 policy_revision BIGINT NOT NULL, state VARCHAR(10) NOT NULL, reason VARCHAR(80) NOT NULL,
 last_contact_at BIGINT NOT NULL, last_evidence_at BIGINT NOT NULL, evidence_key VARCHAR(200) NOT NULL,
 negative_at BIGINT NOT NULL, good_count INT NOT NULL, alarm_open TINYINT NOT NULL,
 report_delayed TINYINT NOT NULL, revision BIGINT NOT NULL,
 CHECK(state IN ('ONLINE','OFFLINE','UNKNOWN')), CHECK(period_seconds BETWEEN 5 AND 86400),
 KEY idx_comm_target_equipment(equip_id,building_id),
 KEY idx_comm_target_source(source_key,identity_id)
);
CREATE TABLE biz_device_comm_event (
 event_id VARCHAR(36) PRIMARY KEY, identity_id VARCHAR(32) NOT NULL, building_id VARCHAR(32) NOT NULL,
 before_state VARCHAR(10) NOT NULL, after_state VARCHAR(10) NOT NULL, reason VARCHAR(80) NOT NULL,
 observed_at BIGINT NOT NULL, policy_revision BIGINT NOT NULL,
 KEY idx_comm_event_identity(identity_id,observed_at,event_id)
);
