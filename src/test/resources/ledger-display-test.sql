DROP TABLE IF EXISTS biz_ledger_config_audit;
DROP TABLE IF EXISTS biz_ledger_equipment_classification;
DROP TABLE IF EXISTS biz_ledger_type_rule;
CREATE TABLE biz_ledger_type_rule (
 type_code VARCHAR(50) PRIMARY KEY, professional_group VARCHAR(20) NOT NULL,
 operation_applicable TINYINT NOT NULL, point_component VARCHAR(20), point_suffix VARCHAR(20),
 evidence VARCHAR(500) NOT NULL, revision BIGINT NOT NULL, updated_by BIGINT,
 CHECK (professional_group IN ('POWER','HVAC','RENEWABLE','WATER','ENVIRONMENT','UNCLASSIFIED')),
 CHECK (operation_applicable IN (0,1)),
 CHECK ((point_component IS NULL AND point_suffix IS NULL) OR (point_component IS NOT NULL AND point_suffix IS NOT NULL)),
 CHECK (revision>0)
);
CREATE TABLE biz_ledger_equipment_classification (
 equipment_id VARCHAR(32) PRIMARY KEY, professional_group VARCHAR(20), evidence VARCHAR(500) NOT NULL,
 revision BIGINT NOT NULL, updated_by BIGINT NOT NULL,
 CHECK (professional_group IS NULL OR professional_group IN ('POWER','HVAC','RENEWABLE','WATER','ENVIRONMENT','UNCLASSIFIED')),
 CHECK (revision>0)
);
CREATE TABLE biz_ledger_config_audit (
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 config_kind VARCHAR(40) NOT NULL, target_id VARCHAR(50) NOT NULL, changed_by BIGINT NOT NULL,
 changed_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP NOT NULL, before_json TEXT NOT NULL, after_json TEXT NOT NULL
);
